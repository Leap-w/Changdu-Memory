/**
 * 根据日期获取每日寄语
 */
export function getDailyQuote(date: Date = new Date()): string {
  const dayOfYear = Math.floor(
    (date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24),
  )
  return QUOTES[dayOfYear % QUOTES.length]
}
